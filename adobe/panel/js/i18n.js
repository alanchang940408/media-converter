  var current = 'zh-TW'

  /** 'zh-TW' | 'en' | 'ja' from an app locale ('ja', 'zh-TW') or a host locale ('ja_JP', 'zh_TW', 'en_US'). */
  function normalize(loc) {
    if (!loc) return null
    var l = String(loc).replace('_', '-').toLowerCase()
    if (l === 'zh-tw' || l === 'zh-hant' || l.indexOf('zh-hant') === 0 || l === 'zh-hk' || l.indexOf('zh') === 0) return 'zh-TW'
    if (l.indexOf('ja') === 0) return 'ja'
    if (l.indexOf('en') === 0) return 'en'
    return null
  }

  MC.i18n = {
    normalize: normalize,
    setLocale: function (loc) {
      current = normalize(loc) || 'en'
      document.documentElement.lang = current
    },
    locale: function () {
      return current
    },
    t: function (key, vars) {
      var s = (dict[current] && dict[current][key]) || dict.en[key] || key
      if (vars) {
        s = s.replace(/\{(\w+)\}/g, function (m, k) {
          return vars[k] === undefined ? m : String(vars[k])
        })
      }
      return s
    }
  }
